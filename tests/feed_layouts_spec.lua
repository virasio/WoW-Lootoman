local Loader = require("tests.helpers.loader")

describe("loot feed layouts", function()
	local ns, Layouts, Storage, module

	local function height()
		return module.feed.options.layout.height
	end

	before_each(function()
		ns = Loader.LoadAddon()
		Loader.Start(ns)
		Layouts, Storage = ns.Feed.Layouts, ns.Storage
		module = ns.Modules:Get("LootFeed")
	end)

	it("always have Default, made from the large design, which every profile uses at first", function()
		assert.same({ "Default" }, Layouts.List())
		assert.same({ "Default", { schema = 1, base = "large" } }, { Layouts.Current(), Layouts.CurrentDesign() })
		assert.equals(Layouts.CurrentDesign(), Storage:GetGlobalSection("feedLayouts").Default)
		assert.equals(35, height())
	end)

	it("start from a built-in design, and are listed Default first, then by name", function()
		assert.equals("Raid", Layouts.Create("Raid", "compact"))
		Layouts.Create("auction", "minimal")
		assert.same({ "Default", "auction", "Raid" }, Layouts.List())
		assert.same({ schema = 1, base = "compact" }, Layouts.Get("Raid"))
		assert.same({ nil, "template" }, { Layouts.Create("Huge", "huge") })
	end)

	it("follow the rules of profile names", function()
		Layouts.Create("Raid", "large")
		assert.same({ nil, "exists" }, { Layouts.Create("raid", "large") })
		assert.same({ nil, "exists" }, { Layouts.Create("default", "large") })
		assert.same({ nil, "empty" }, { Layouts.Create("  ", "large") })
		assert.same({ nil, "too_long" }, { Layouts.Create(("x"):rep(49), "large") })
		assert.equals("Solo", Layouts.Create("  Solo ", "large"))
	end)

	it("are used per profile, and a profile whose layout is gone uses Default", function()
		Layouts.Create("Raid", "compact")
		assert.is_true(Layouts.Use("Raid"))
		assert.same({ "Raid", 24 }, { Layouts.Current(), height() })
		ns.Profiles.Switch(ns.Profiles.Create("Other"))
		assert.same({ "Default", 35 }, { Layouts.Current(), height() })
		Storage:Set("LootFeed", "layout", "Gone")
		assert.equals("Default", Layouts.Current())
		assert.same({ nil, "missing" }, { Layouts.Use("Gone") })
	end)

	it("are shared: a change shows in every profile that uses the layout", function()
		Layouts.Create("Raid", "large")
		Layouts.Use("Raid")
		ns.Profiles.Switch(ns.Profiles.Copy("Default", "Other"))
		ns.Feed.Design.Set(Layouts.CurrentDesign(), "row", "height", 40)
		ns.Profiles.Switch("Default")
		assert.equals(40, height())
	end)

	it("are copied whole, and the copy is the layout's own", function()
		ns.Feed.Design.Set(Layouts.Get("Default"), "row", "height", 40)
		assert.equals("Mine", Layouts.Copy("Default", "Mine"))
		ns.Feed.Design.Set(Layouts.Get("Mine"), "row", "height", 50)
		assert.same({ 40, 50 }, { Layouts.Get("Default").changes.row.height, Layouts.Get("Mine").changes.row.height })
		assert.same({ nil, "missing" }, { Layouts.Copy("Gone", "Other") })
	end)

	it("are renamed in every profile that uses them, and the feed keeps its look", function()
		Layouts.Create("Raid", "compact")
		Layouts.Use("Raid")
		ns.Profiles.Switch(ns.Profiles.Copy("Default", "Other"))
		assert.equals("Dungeon", Layouts.Rename("Raid", "Dungeon"))
		assert.same({ "Dungeon", 24 }, { Layouts.Current(), height() })
		ns.Profiles.Switch("Default")
		assert.equals("Dungeon", Layouts.Current())
		assert.same({ nil, "default" }, { Layouts.Rename("Default", "Main") })
		assert.same({ nil, "exists" }, { Layouts.Rename("Dungeon", "default") })
		assert.equals("dungeon", Layouts.Rename("Dungeon", "dungeon"))
	end)

	it("are deleted, and their profiles use Default", function()
		Layouts.Create("Raid", "compact")
		Layouts.Use("Raid")
		assert.is_true(Layouts.Delete("Raid"))
		assert.same({ "Default", 35, { "Default" } }, { Layouts.Current(), height(), Layouts.List() })
		assert.equals("Default", Storage:Get("LootFeed", "layout"))
		assert.same({ nil, "default" }, { Layouts.Delete("Default") })
		assert.same({ nil, "missing" }, { Layouts.Delete("Raid") })
	end)

	it("go back to their template on reset, and the feed follows", function()
		Layouts.Create("Raid", "compact")
		Layouts.Use("Raid")
		ns.Feed.Design.Set(Layouts.Get("Raid"), "row", "height", 40)
		module:Apply()
		assert.equals(40, height())
		assert.is_true(Layouts.Reset("Raid"))
		assert.same({ { schema = 1, base = "compact" }, 24 }, { Layouts.Get("Raid"), height() })
	end)

	it("tell which name a new one would clash with, and find a free one like it", function()
		Layouts.Create("Raid", "large")
		Layouts.Create("Raid 2", "large")
		assert.same({ "Raid", "Default", nil }, { Layouts.Taken("RAID"), Layouts.Taken("default"), Layouts.Taken("Solo") })
		assert.same({ "Raid 3", "Solo" }, { Layouts.FreeName("Raid"), Layouts.FreeName("Solo") })
	end)

	it("find a free name within the longest name allowed, shortening the name by characters", function()
		local latin = ("a"):rep(47) .. "b"
		local cyrillic = ("я"):rep(47) .. "ж"
		Layouts.Create(latin, "large")
		Layouts.Create(cyrillic, "large")
		assert.equals(("a"):rep(46) .. " 2", Layouts.FreeName(latin))
		assert.equals(("я"):rep(46) .. " 2", Layouts.FreeName(cyrillic))
		local free = Layouts.FreeName(cyrillic)
		assert.equals(free, Layouts.Create(free, "large"))
		assert.equals(("я"):rep(46) .. " 3", Layouts.FreeName(cyrillic))
	end)
end)
