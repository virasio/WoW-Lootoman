local Loader = require("tests.helpers.loader")

-- Feed looks: named sets of every loot feed setting with the row design.
describe("loot feed looks", function()
	local ns, Looks, Storage, sent

	before_each(function()
		ns = Loader.LoadAddon()
		Loader.Start(ns)
		Looks, Storage = ns.Feed.Looks, ns.Storage
		sent = {}
		ns.Bus:On("FeedLookChanged", sent, function(_, name, key)
			sent[#sent + 1] = name .. ":" .. tostring(key)
		end)
	end)

	it("always have Default, with the Large design, which every profile uses at first", function()
		assert.same({ "Default" }, Looks.List())
		assert.same({ "Default", "rows" }, { Looks.Current(), Looks.View("Default") })
		assert.same({ schema = 1, base = "large" }, Storage:GetGlobalSection("feedLooks").Default)
		assert.equals("Default", ns.L["Default"] and Looks.DisplayName("Default"))
	end)

	it("start with the Large design and every setting at its default, listed Default first, then by name", function()
		assert.equals("Raid", Looks.Create("Raid"))
		Looks.Create("auction")
		assert.same({ "Default", "auction", "Raid" }, Looks.List())
		assert.same({ schema = 1, base = "large" }, Looks.Get("Raid"))
		assert.same({ 5, true, false, 12, 0, 3, true }, { Looks.Value("Raid", "maxRows"), Looks.Value("Raid", "xp"),
			Looks.Value("Raid", "keepPets"), Looks.Value("Raid", "size"), Looks.Value("Raid", "backgroundOpacity"),
			Looks.Value("Raid", "warnGeneralAt"), Looks.Value("Raid", "warnReagent") })
	end)

	it("follow the rules of profile names", function()
		Looks.Create("Raid")
		assert.same({ nil, "exists" }, { Looks.Create("raid") })
		assert.same({ nil, "exists" }, { Looks.Create("default") })
		assert.same({ nil, "empty" }, { Looks.Create("  ") })
		assert.same({ nil, "too_long" }, { Looks.Create(("x"):rep(49)) })
		assert.equals("Solo", Looks.Create("  Solo "))
		assert.equals("Raid 2", Looks.FreeName("Raid"))
	end)

	it("keep only the settings that differ from the defaults, and refuse what their controls cannot set", function()
		assert.is_true(Looks.Set("Default", "maxRows", 8))
		assert.same({ maxRows = 8 }, Looks.Get("Default").values)
		Looks.Set("Default", "maxRows", 5)
		assert.is_nil(Looks.Get("Default").values)
		assert.same({ nil, "value" }, { Looks.Set("Default", "maxRows", 2) })
		assert.same({ nil, "value" }, { Looks.Set("Default", "maxRows", 7.5) })
		assert.same({ nil, "value" }, { Looks.Set("Default", "maxRows", "8") })
		assert.same({ nil, "value" }, { Looks.Set("Default", "minQuality", 9) })
		assert.same({ nil, "value" }, { Looks.Set("Default", "nothing", true) })
		assert.same({ nil, "missing" }, { Looks.Set("Gone", "xp", false) })
		-- A changed value is announced; the same value again is not.
		Looks.Set("Default", "xp", false)
		Looks.Set("Default", "xp", false)
		assert.same({ "Default:maxRows", "Default:maxRows", "Default:xp" }, sent)
		-- A stored value it cannot hold counts as the default.
		Looks.Get("Default").values = { size = 99, glow = "yes" }
		assert.same({ 12, true }, { Looks.Value("Default", "size"), Looks.Value("Default", "glow") })
	end)

	it("fill up or down with rows, in any direction with icons, each view from its own default", function()
		assert.same({ nil, "value" }, { Looks.Set("Default", "direction", "left") })
		assert.is_true(Looks.Set("Default", "direction", "down"))
		Looks.Create("Strip")
		assert.is_true(Looks.SetView("Strip", "icons"))
		assert.same({ "icons", "right" }, { Looks.View("Strip"), Looks.Value("Strip", "direction") })
		assert.is_true(Looks.Set("Strip", "direction", "left"))
		assert.same({ nil, "view" }, { Looks.SetView("Strip", "tiles") })
	end)

	it("start their design afresh, and their direction from the view's, when the view changes", function()
		Looks.Create("Strip")
		Looks.SetDesign("Strip", "name", "fontSize", 15)
		Looks.Set("Strip", "direction", "down")
		Looks.Set("Strip", "maxRows", 9)
		sent = {}
		Looks.SetView("Strip", "icons")
		assert.same({ schema = 1, base = "icons", values = { maxRows = 9 } }, Looks.Get("Strip"))
		assert.same({ "Strip:nil" }, sent)
		Looks.SetView("Strip", "rows")
		assert.same({ "rows", "up" }, { Looks.View("Strip"), Looks.Value("Strip", "direction") })
	end)

	it("change their design through Design, and say so", function()
		assert.equals(15, Looks.SetDesign("Default", "name", "fontSize", 15))
		assert.same({ name = { fontSize = 15 } }, Looks.Get("Default").changes)
		assert.same({ "Default:nil" }, sent)
		assert.has_error(function() Looks.SetDesign("Default", "name", "align", "MIDDLE") end)
	end)

	it("are used by the current profile, and moved off when renamed or deleted", function()
		local changed = {}
		ns.Bus:On("SettingChanged", changed, function(_, module, key, value)
			changed[#changed + 1] = ("%s.%s=%s"):format(module, key, tostring(value))
		end)
		Looks.Create("Raid")
		assert.is_true(Looks.Use("Raid"))
		assert.same({ nil, "missing" }, { Looks.Use("Gone") })
		assert.equals("Raid", Looks.Current())
		assert.equals("Party", Looks.Rename("Raid", "Party"))
		assert.equals("Party", Storage:Get("LootFeed", "look"))
		assert.same({ nil, "default" }, { Looks.Rename("Default", "Main") })
		assert.is_true(Looks.Delete("Party"))
		assert.same({ "Default", "Default" }, { Looks.Current(), Storage:Get("LootFeed", "look") })
		assert.same({ nil, "default" }, { Looks.Delete("Default") })
		assert.same({ "LootFeed.look=Raid", "LootFeed.look=Party", "LootFeed.look=Default" }, changed)
	end)

	it("copy everything, and reset to every default and a fresh design in their view", function()
		Looks.Create("Strip")
		Looks.SetView("Strip", "icons")
		Looks.Set("Strip", "maxRows", 10)
		Looks.SetDesign("Strip", "amount", "fontSize", 15)
		assert.equals("Copy", Looks.Copy("Strip", "Copy"))
		assert.same(Looks.Get("Strip"), Looks.Get("Copy"))
		assert.are_not.equal(Looks.Get("Strip"), Looks.Get("Copy"))
		Looks.Reset("Copy")
		assert.same({ schema = 1, base = "icons" }, Looks.Get("Copy"))
	end)

	it("are cleaned for a profile text: their design and only the settings they may hold", function()
		local look = Looks.Clean({ schema = 1, base = "icons", changes = { amount = { fontSize = 15 } },
			values = { direction = "left", maxRows = 40, xp = false, nothing = 1 } })
		assert.same({ schema = 1, base = "icons", changes = { amount = { fontSize = 15 } }, values = { direction = "left", xp = false } }, look)
		-- A rows look cannot fill sideways.
		assert.same({ schema = 1, base = "large" }, Looks.Clean({ schema = 1, base = "large", values = { direction = "left" } }))
		assert.same({ nil, "newer" }, { Looks.Clean({ schema = 9, base = "large" }) })
		Looks.Put("Imported", look)
		assert.same({ "Default", "Imported" }, Looks.List())
		assert.same({ "Imported:nil" }, sent)
	end)
end)
